/**
 * ============================================================================
 * DOT-MATRIX WORLD MAP
 * ============================================================================
 * The map is not an image and not an SVG of country borders. At build time we
 * rasterise a set of coarse coastline polygons into a 1-bit landmask, ship it
 * as ~2.5 KB of base64, and the runtime paints it as a grid of glowing dots on
 * a canvas. That keeps the "network of light" look while costing less than a
 * single map tile.
 *
 * Coordinates are [longitude, latitude]. Outlines are deliberately coarse —
 * at 1.6° per cell nothing finer would survive anyway.
 * ============================================================================
 */

