function inPolygon(lon, lat, poly) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/** Longitude/latitude → fractional grid coordinates (0..cols, 0..rows). */
export function project(lon, lat) {
  return {
    x: ((lon + 180) / GRID.lonSpan) * GRID.cols,
    y: ((GRID.latTop - lat) / GRID.latSpan) * GRID.rows,
  };
}

/**
 * Rasterise the polygons into a packed 1-bit mask, row-major, MSB first.
 * @returns {string} base64
 */
export function buildMask() {
  const { cols, rows, cell, latTop } = GRID;
  const bytes = new Uint8Array(Math.ceil((cols * rows) / 8));
  let land = 0;
  for (let r = 0; r < rows; r++) {
    const lat = latTop - (r + 0.5) * cell;
    for (let c = 0; c < cols; c++) {
      const lon = -180 + (c + 0.5) * cell;
      let hit = false;
      for (const poly of LAND) {
        if (inPolygon(lon, lat, poly)) {
          hit = true;
          break;
        }
      }
      if (hit) {
        const bit = r * cols + c;
        bytes[bit >> 3] |= 128 >> (bit & 7);
        land++;
      }
    }
  }
  return { b64: Buffer.from(bytes).toString('base64'), land, total: cols * rows };
}
